import {chromium} from 'playwright';
import {createDevServer} from '../dev-server.mjs';
import {mkdtemp,mkdir,writeFile,readFile,rm,cp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';

const temp=await mkdtemp(join(tmpdir(),'form-components-')),project=join(temp,'project'),editorDir=join(temp,'editor');
await mkdir(project);
await writeFile(join(project,'index.html'),'<!doctype html><html><body><div id="host" style="position:relative;width:1100px;height:900px"></div></body></html>');
await cp(resolve('.'),editorDir,{recursive:true,filter:p=>!['.git','node_modules','.editor-workspaces','editor-config.json'].includes(p.split(/[\\/]/).pop())});
const server=createDevServer({rootDir:temp,editorDir});await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;
const projectInfo=await(await fetch(base+'/api/projects/open',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({path:project})})).json();
const browser=await chromium.launch();
try {
  const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
  page.setDefaultTimeout(6000);page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${base}/editor/editor.html?project=${projectInfo.id}&entry=index.html`);
  const frame=page.frameLocator('#prototype-frame');await frame.locator('body[data-ve-editor-ready=true]').waitFor();
  async function saveSource() {
    const request=page.waitForResponse(r=>r.url().includes('/api/source-save') && r.request().method()==='POST');
    await page.locator('#save-button').click();
    const response=await request;assert.equal(response.status(),200,await response.text());
    await page.locator('#source-dialog').waitFor({state:'hidden'});
    await frame.locator('body[data-ve-editor-ready=true]').waitFor();
  }
  await page.locator('[data-mode=edit]').click();
  if(!await page.locator('#structure-panel').isVisible())await page.locator('#layers-toggle').click();
  await page.locator('[data-structure-tab=insert]').click();
  for(const [type,label,tag] of [['select','下拉框','select'],['input','输入框','input']]) {
    const button=page.locator(`[data-insert="${type}"]`);
    assert.equal(await button.count(),1,`${label} is available in the palette`);
    assert.match(await button.textContent(),new RegExp(label));
    assert.equal(await button.locator('svg').count(),1);
    await frame.locator('#host').click({position:{x:800,y:600},modifiers:['Alt']});
    await button.click();
    const control=frame.locator(`${tag}[data-editor-component="${type}"]`);await control.waitFor();
    assert.equal(await control.evaluate(el=>el.getBoundingClientRect().width),240);
    await frame.locator('#host').click({position:{x:800,y:600}});
    await control.click({position:{x:10,y:10}});
    assert.ok(await control.evaluate(el=>el.classList.contains('ve-selected')),`${label} is selectable`);
    await page.keyboard.press('Escape');
    assert.equal(await frame.locator('.ve-selected').count(),0,`${label} deselects with Escape`);
    await control.click({position:{x:10,y:10}});
    await frame.locator('#host').click({position:{x:800,y:600}});
    assert.equal(await frame.locator('.ve-selected').count(),0,`${label} deselects by clicking canvas whitespace`);
    await control.click({position:{x:10,y:10}});
    const beforeDrag=await control.boundingBox();
    await page.mouse.move(beforeDrag.x+10,beforeDrag.y+10);await page.mouse.down();
    await page.mouse.move(beforeDrag.x+50,beforeDrag.y+30,{steps:3});await page.mouse.up();
    const afterDrag=await control.boundingBox();
    assert.ok(afterDrag.x>beforeDrag.x+5,`${label} can be dragged while editing`);
    await page.locator('#undo-button').click();await control.waitFor();
    await control.click({position:{x:10,y:10}});
    await page.keyboard.press('Backspace');
    assert.equal(await control.count(),0,`${label} must delete as a component instead of consuming Backspace`);
    await page.locator('#undo-button').click();await control.waitFor();
    await control.click({position:{x:10,y:10}});
    assert.equal(await control.evaluate(el=>el===el.ownerDocument.activeElement),false,'edit mode must not focus the native field');
    await page.locator('#delete-button').click();await control.waitFor({state:'detached'});
    await page.locator('#undo-button').click();await control.waitFor();
  }
  await page.locator('#undo-button').click();await frame.locator('input[data-editor-component]').waitFor({state:'detached'});
  await frame.locator('body[data-ve-editor-ready=true]').waitFor();
  await page.locator('#redo-button').click();await frame.locator('input[data-editor-component]').waitFor();
  await saveSource();
  await page.reload();await frame.locator('body[data-ve-editor-ready=true]').waitFor();
  assert.equal(await frame.locator('input[data-editor-component="input"]').count(),1);
  assert.equal(await frame.locator('select[data-editor-component="select"]').count(),1);
  await page.locator('[data-mode=edit]').click();
  await frame.locator('input').click();
  const formSection=page.locator('#card-section');
  assert.equal(await formSection.isVisible(),true,'input content settings are visible in the sidebar');
  await formSection.getByRole('textbox',{name:'提示文字',exact:true}).fill('请输入客户名称');
  await formSection.getByRole('button',{name:'应用表单内容'}).click();
  assert.equal(await frame.locator('input').getAttribute('placeholder'),'请输入客户名称');
  for(let i=0;i<6;i++)await page.keyboard.press('Shift+ArrowDown');
  const textEditor=page.locator('#editor-form-text-edit');
  await frame.locator('input').dblclick();await textEditor.waitFor();
  await textEditor.fill('输入内容');await page.keyboard.press('Backspace');
  assert.equal(await frame.locator('input').count(),1,'Backspace edits text during double-click editing');
  await page.keyboard.press('Enter');await textEditor.waitFor({state:'detached'});
  assert.equal(await frame.locator('input').inputValue(),'输入内');
  await page.locator('#undo-button').click();assert.equal(await frame.locator('input').inputValue(),'');
  await page.locator('#redo-button').click();assert.equal(await frame.locator('input').inputValue(),'输入内');
  await frame.locator('select').dblclick();await textEditor.waitFor();
  await textEditor.fill('选择渠道');await page.keyboard.press('Enter');
  assert.equal(await frame.locator('select option').first().textContent(),'选择渠道');
  await frame.locator('select').click();
  for(const [i,text] of ['微信','邮件','电话'].entries())await formSection.getByRole('textbox',{name:`选项 ${i+1}`,exact:true}).fill(text);
  await formSection.getByRole('button',{name:'应用表单内容'}).click();
  assert.deepEqual(await frame.locator('select option').evaluateAll(ns=>ns.map(n=>n.textContent)),['选择渠道','微信','邮件','电话']);
  await frame.locator('input').dblclick();await textEditor.fill('取消的修改');await page.keyboard.press('Escape');
  assert.equal(await frame.locator('input').inputValue(),'输入内','Escape cancels text edits');
  await frame.locator('input').dblclick();await textEditor.fill('失焦提交');
  await frame.locator('#host').click({position:{x:800,y:600}});
  await textEditor.waitFor({state:'detached'});assert.equal(await frame.locator('input').inputValue(),'失焦提交');
  await saveSource();
  assert.match(await readFile(join(project,'index.html'),'utf8'),/placeholder="请输入客户名称"/,'sidebar edit is physically saved');
  await page.reload();await frame.locator('body[data-ve-editor-ready=true]').waitFor();
  assert.equal(await frame.locator('input').inputValue(),'失焦提交','input text survives save and reload');
  assert.equal(await frame.locator('select option').first().textContent(),'选择渠道','dropdown text survives save and reload');
  assert.equal(await frame.locator('input').getAttribute('placeholder'),'请输入客户名称','sidebar placeholder survives save and reload');
  assert.deepEqual(await frame.locator('select option').evaluateAll(ns=>ns.map(n=>n.textContent)),['选择渠道','微信','邮件','电话'],'sidebar option labels survive save and reload');
  await page.locator('[data-mode=preview]').click();
  await frame.locator('input').fill('预览输入');
  await page.keyboard.press('Backspace');assert.equal(await frame.locator('input').inputValue(),'预览输');
  await frame.locator('select').selectOption('option-2');assert.equal(await frame.locator('select').inputValue(),'option-2');
  await frame.locator('input').focus();
  await page.locator('[data-mode=edit]').click();await frame.locator('input').click();
  await page.keyboard.press('Delete');assert.equal(await frame.locator('input').count(),0,'switching back to editing restores component deletion');
  await page.locator('#undo-button').click();await frame.locator('input').waitFor();
  const saved=await readFile(join(project,'index.html'),'utf8');assert.match(saved,/placeholder="请输入客户名称"/);
  const standalone=await browser.newPage();await standalone.goto(`file://${join(project,'index.html')}`);
  await standalone.locator('input').fill('测试内容');assert.equal(await standalone.locator('input').inputValue(),'测试内容');
  await standalone.locator('select').selectOption('option-2');assert.equal(await standalone.locator('select').inputValue(),'option-2');
  assert.deepEqual(errors,[]);
  console.log('PASS: form insert, selection, Escape and blank deselection, drag, keyboard and button deletion, undo/redo, save/reload and preview typing');
} finally {await browser.close();await new Promise(r=>server.close(r));await rm(temp,{recursive:true,force:true});}

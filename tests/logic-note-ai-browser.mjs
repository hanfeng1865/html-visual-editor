import {chromium} from 'playwright';
import {createDevServer} from '../dev-server.mjs';
import {mkdtemp,cp,writeFile,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import assert from 'node:assert/strict';
const temp=await mkdtemp(join(tmpdir(),'logic-note-ai-')),project=join(temp,'project'),editorDir=join(temp,'editor');
await mkdir(project);
await cp(new URL('../',import.meta.url),editorDir,{recursive:true,filter:path=>!['.git','node_modules','.editor-workspaces','editor-config.json','output'].includes(path.split(/[\\/]/).pop())});
await writeFile(join(project,'index.html'),'<style>body{margin:0;min-height:700px}#area{margin:70px;width:700px;height:400px;background:#eee}#target{margin:60px;width:90px;height:32px}</style><section id="area"><button id="target">新增车辆</button></section>');
const server=createDevServer({rootDir:temp,editorDir});await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;
const post=(url,value)=>fetch(base+url,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(value)});
const config=await(await post('/api/projects/open',{path:project})).json();
const endpoint=`/api/change-annotations?project=${config.id}&entry=index.html`;
await post(endpoint,{version:1,hidden:[],boxes:[{id:'one',selector:'#target',cockpit:'page',context:'',x:0,y:0,width:1,height:1}],notes:{'box:one':'说明保留'},colors:{'box:one':'red'}});
const browser=await chromium.launch();
try{
 const page=await browser.newPage({viewport:{width:1700,height:1000}});page.setDefaultTimeout(5000);
 await page.goto(`${base}/editor/editor.html?project=${config.id}&entry=index.html`);
 const f=page.frameLocator('#prototype-frame');await f.locator('body[data-ve-editor-ready=true]').waitFor();
 await page.locator('#editor-changes-toggle').click();
 const card=page.locator('.annotation-card');
 let calls=0,last;
 await page.route('**/api/change-annotations/ai?*',async route=>{
  calls++;last=route.request().postDataJSON();
  await new Promise(r=>setTimeout(r,200));
  await route.fulfill({json:{content:'操作：点击新增车辆打开表单。\n校验：车牌号必填。'}});
 });
 assert.equal(calls,0,'opening annotations never calls AI');
 await card.getByRole('button',{name:'编辑说明',exact:true}).click();
 const area=card.locator('textarea');
 await page.waitForFunction(()=>document.querySelector('.annotation-card textarea').getBoundingClientRect().width>=420);
 assert.ok((await area.boundingBox()).height>=240,'editing starts with a generous height');
 await area.fill(Array.from({length:18},(_,i)=>`规则 ${i+1}：填写车辆信息后保存。`).join('\n'));
 await page.waitForFunction(()=>{const el=document.querySelector('.annotation-card textarea');return el.clientHeight>=el.scrollHeight-2;});
 assert.ok((await area.boundingBox()).height>360,'long notes grow instead of staying in a tiny scroller');
 await card.getByRole('button',{name:'取消',exact:true}).click();
 await card.getByRole('button',{name:'编辑说明',exact:true}).click();
 assert.equal(await area.inputValue(),'说明保留','cancel keeps the saved note');
 await card.locator('textarea').fill('新增时车牌号必填');
 await card.getByRole('button',{name:'AI 润色',exact:true}).click();
 await card.getByRole('button',{name:'采用草稿',exact:true}).waitFor();
 assert.equal(await card.locator('.annotation-ai-preview .annotation-note-line').count(),2,'preview separates rules into readable lines');
 assert.equal(await card.locator('.annotation-ai-preview strong.annotation-note-label').first().textContent(),'操作：');
 assert.equal(calls,1);assert.equal(last.mode,'polish');assert.equal(last.note,'新增时车牌号必填');
 assert.ok(last.snapshot.htmlGzip||last.snapshot.html);assert.ok(last.region.width>0);
 assert.equal(await card.locator('textarea').inputValue(),'新增时车牌号必填','AI must not overwrite input');
 assert.equal((await(await fetch(base+endpoint)).json()).notes['box:one'],'说明保留');
 await card.getByRole('button',{name:'采用草稿',exact:true}).click();
 await card.getByRole('button',{name:'保存说明',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.annotation-card-note')?.textContent.includes('点击新增车辆打开表单'));
 await page.reload();await f.locator('body[data-ve-editor-ready=true]').waitFor();await page.locator('#editor-changes-toggle').click();
 assert.match(await card.textContent(),/点击新增车辆打开表单/);
 assert.equal(await card.locator('p.annotation-card-note > .annotation-note-line').count(),2,'saved note keeps the same readable layout after reload');
 await card.getByRole('button',{name:'AI 生成说明',exact:true}).click();
 await card.getByRole('button',{name:'采用草稿',exact:true}).waitFor();assert.equal(last.mode,'generate');
 await card.getByRole('button',{name:'放弃草稿',exact:true}).click();
 assert.match(await card.textContent(),/点击新增车辆打开表单/);
 await page.unroute('**/api/change-annotations/ai?*');
 await page.route('**/api/change-annotations/ai?*',route=>route.fulfill({status:502,json:{error:'模型连接失败'}}));
 await card.getByRole('button',{name:'AI 生成说明',exact:true}).click();
 await card.getByText('模型连接失败',{exact:true}).waitFor();
 assert.match(await card.textContent(),/点击新增车辆打开表单/);
 const longNote=Array.from({length:18},(_,i)=>`规则 ${i+1}：车辆信息需完成校验后保存。`).join('\n');
 await post(endpoint,{version:1,hidden:[],boxes:[{id:'one',selector:'#target',cockpit:'page',context:'',x:0,y:0,width:1,height:1},{id:'two',selector:'#area',cockpit:'page',context:'',x:0,y:0,width:.5,height:.5}],notes:{'box:one':longNote,'box:two':'第二条说明'},colors:{}});
 await page.reload();await f.locator('body[data-ve-editor-ready=true]').waitFor();await page.locator('#editor-changes-toggle').click();
 const longCard=page.locator('.annotation-card[data-annotation-id="one"]');
 const toggle=longCard.getByRole('button',{name:'放大查看',exact:true});await toggle.waitFor();
 const collapsed=await longCard.locator(':scope > p.annotation-card-note').boundingBox();assert.ok(collapsed.height<=150,'long note stays compact by default');
 assert.ok(await page.locator('.annotation-card[data-annotation-id="two"]').isVisible(),'next card stays visible');
 await toggle.click();
 const reader=page.getByRole('dialog',{name:'逻辑 1 · 完整说明',exact:true});await reader.waitFor();
 assert.ok((await reader.boundingBox()).width>=700,'full note opens in a wide reader');
 assert.equal(await reader.locator('.annotation-reader-content').textContent(),longNote,'reader shows complete content');
 assert.ok((await longCard.locator(':scope > p.annotation-card-note').boundingBox()).height<=150,'sidebar stays compact');
 await reader.getByRole('button',{name:'关闭',exact:true}).click();await reader.waitFor({state:'detached'});
 await toggle.click();await reader.waitFor();await page.keyboard.press('Escape');await reader.waitFor({state:'detached'});

 await longCard.getByRole('button',{name:'编辑说明',exact:true}).click();
 assert.equal(await longCard.locator('textarea').inputValue(),longNote,'editing gets the complete note');
 await longCard.getByRole('button',{name:'取消',exact:true}).click();
 await longCard.getByRole('button',{name:'放大查看',exact:true}).waitFor();
 assert.equal((await(await fetch(base+endpoint)).json()).notes['box:one'],longNote,'folding never changes saved content');
 console.log('PASS: explicit generation, unsaved text polishing, screenshot context, review, persistence and error preservation');
}finally{await browser.close();await new Promise(r=>server.close(r));await rm(temp,{recursive:true,force:true});}

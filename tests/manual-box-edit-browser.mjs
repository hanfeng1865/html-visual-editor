import {chromium} from 'playwright';
import {createDevServer} from '../dev-server.mjs';
import {mkdtemp,cp,writeFile,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import assert from 'node:assert/strict';
const temp=await mkdtemp(join(tmpdir(),'manual-box-edit-')),project=join(temp,'project'),editorDir=join(temp,'editor');
await mkdir(project);
await cp(new URL('../',import.meta.url),editorDir,{recursive:true,filter:path=>!['.git','node_modules','.editor-workspaces','editor-config.json','output'].includes(path.split(/[\\/]/).pop())});
await writeFile(join(project,'index.html'),'<style>body{margin:0;min-height:700px}#area{margin:70px;width:700px;height:400px;background:#eee}#target{margin:60px;width:90px;height:32px}</style><section id="area"><button id="target">新增车辆</button></section>');
const server=createDevServer({rootDir:temp,editorDir});await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;
const post=(url,value)=>fetch(base+url,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(value)});
const config=await(await post('/api/projects/open',{path:project})).json();
const endpoint=`/api/change-annotations?project=${config.id}&entry=index.html`;
await post(endpoint,{version:1,hidden:[],boxes:[{id:'one',selector:'#target',cockpit:'page',context:'',x:0,y:0,width:1,height:1}],notes:{'box:one':'说明保留'},colors:{'box:one':'red'}});
const browser=await chromium.launch();
try{
 const page=await browser.newPage({viewport:{width:1700,height:1000}});page.setDefaultTimeout(5000);
 await page.goto(`${base}/editor/editor.html?project=${config.id}&entry=index.html`);
 const f=page.frameLocator('#prototype-frame');await f.locator('body[data-ve-editor-ready=true]').waitFor();
 await page.locator('#editor-changes-toggle').click();
 const marker=f.locator('.editor-change-marker');await marker.waitFor();
 const badge=marker.getByRole('button',{name:'查看第 1 项逻辑说明',exact:true});
 const placement=await badge.evaluate(e=>({w:e.offsetWidth,h:e.offsetHeight,left:e.offsetLeft,top:e.offsetTop}));
 assert.ok(placement.w<=18&&placement.h<=18,'number should be compact');
 assert.ok(placement.left<10&&placement.top<10,'number sits in the upper-left corner');
 await marker.getByRole('button',{name:'选中并调整改动框范围',exact:true}).click();
 const drag=async(locator,dx,dy)=>{const r=await locator.boundingBox();const fraction=(await locator.getAttribute('data-move-edge')) ? .25 : .5;const startX=r.x+r.width*fraction,startY=r.y+r.height/2;await page.mouse.move(startX,startY);await page.mouse.down();await page.mouse.move(startX+dx,startY+dy,{steps:8});await page.mouse.up();};
 const before=await marker.boundingBox();
 await drag(marker.locator('[data-resize-direction="se"]'),80,45);
 await page.waitForFunction(()=>!document.querySelector('#editor-box-toggle').disabled);
 let enlarged=await marker.boundingBox();assert.ok(enlarged.width>before.width+50&&enlarged.height>before.height+20,'existing box grows beyond original button');
 await drag(marker.locator('[data-move-edge="top"]'),45,30);
 let moved=await marker.boundingBox();assert.ok(moved.x>enlarged.x+25&&moved.y>enlarged.y+15,'box moves without resizing');
 assert.ok(Math.abs(moved.width-enlarged.width)<3&&Math.abs(moved.height-enlarged.height)<3);
 await drag(marker.locator('[data-resize-direction="se"]'),-30,-15);
 const shrunk=await marker.boundingBox();assert.ok(shrunk.width<moved.width-15,'existing box shrinks');
 const saved=await(await fetch(base+endpoint)).json();assert.equal(saved.notes['box:one'],'说明保留');assert.equal(saved.boxes[0].id,'one');
 await page.reload();await f.locator('body[data-ve-editor-ready=true]').waitFor();await page.locator('#editor-changes-toggle').click();
 await page.waitForFunction(width=>{const frame=document.getElementById('prototype-frame'),marker=frame.contentDocument.querySelector('.editor-change-marker');return marker&&Math.abs(marker.getBoundingClientRect().width*frame.getBoundingClientRect().width/frame.clientWidth-width)<3;},shrunk.width);
 const restored=await marker.boundingBox();assert.ok(Math.abs(restored.width-shrunk.width)<3,'edited geometry survives reload');
 assert.match(await page.locator('#annotation-rail').textContent(),/说明保留/);

 // A tight control selection must remain attached when its surrounding section grows.
 await post(endpoint,{version:1,hidden:[],boxes:[],notes:{},colors:{}});
 await page.reload();await f.locator('body[data-ve-editor-ready=true]').waitFor();
 await page.locator('#editor-changes-toggle').click();
 const target=f.locator('#target'),targetBounds=await target.boundingBox();
 await page.locator('#editor-box-toggle').click();
 await page.mouse.move(targetBounds.x-3,targetBounds.y-3);await page.mouse.down();
 await page.mouse.move(targetBounds.x+targetBounds.width+3,targetBounds.y+targetBounds.height+3,{steps:6});await page.mouse.up();
 await marker.waitFor();
 await page.waitForFunction(()=>document.querySelector('.annotation-card'));
 const newBox=await(await fetch(base+endpoint)).json();
 assert.equal(newBox.boxes[0].selector,'#target','control selection anchors to the control instead of the surrounding section');
 const checkAlignment=async()=>{
  const result=await f.locator('#target').evaluate(target=>{
   const a=target.getBoundingClientRect(),b=document.querySelector('.editor-change-marker').getBoundingClientRect();
   return {x:b.left-a.left,y:b.top-a.top,width:b.width,height:b.height};
  });
  assert.ok(Math.abs(result.x+5)<2&&Math.abs(result.y+5)<2,'marker stays aligned with the selected control');
  return result;
 };
 const initial=await checkAlignment();
 await f.locator('#area').evaluate(area=>{area.style.height='1800px';});
 await page.setViewportSize({width:1690,height:1000});
 await page.waitForTimeout(150);
 const grown=await checkAlignment();
 assert.ok(Math.abs(initial.height-grown.height)<2,'surrounding content height does not resize a control marker');
 await target.evaluate(target=>target.ownerDocument.defaultView.scrollTo(0,60));
 await page.waitForTimeout(150);await checkAlignment();
 console.log('PASS: compact corner number, grow beyond original anchor, move, shrink and persist manual box');
}finally{await browser.close();await new Promise(r=>server.close(r));await rm(temp,{recursive:true,force:true});}
